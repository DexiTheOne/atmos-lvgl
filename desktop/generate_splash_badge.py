"""Pack the official "Made for ESPHome" badge (esphome.io/images/made-for-esphome-black-on-white.png)
into a 1-bit bitmap for the boot splash. Anything clearly darker than the pale background,
including the cyan logo, becomes ink. Run: python desktop/generate_splash_badge.py"""
from pathlib import Path
from PIL import Image
WIDTH, CUT = 240, 80
here = Path(__file__).parent
im = Image.open(here / 'assets/made-for-esphome-black-on-white.png').convert('RGB')
px = im.load(); mask = Image.new('L', im.size)
m = mask.load()
for y in range(im.size[1]):
    for x in range(im.size[0]):
        m[x, y] = 255 if min(px[x, y]) < 150 else 0
h = round(WIDTH * im.size[1] / im.size[0])
small = mask.resize((WIDTH, h), Image.BOX).load()
stride = (WIDTH + 7) // 8
data = []
for y in range(h):
    row = [0] * stride
    for x in range(WIDTH):
        if small[x, y] > CUT: row[x >> 3] |= 0x80 >> (x & 7)
    data += row
lines = [', '.join('0x%02x' % b for b in data[i:i + stride]) for i in range(0, len(data), stride)]
(here / 'splash_badge.h').write_text(
    '/* Generated by generate_splash_badge.py from the official "Made for ESPHome" badge. 1 = ink, MSB first. */\n'
    '#pragma once\n#include <stdint.h>\n'
    f'#define SPLASH_BADGE_W {WIDTH}\n#define SPLASH_BADGE_H {h}\n'
    'static const uint8_t splash_badge[SPLASH_BADGE_H][(SPLASH_BADGE_W+7)/8] = {\n' +
    ''.join('    {%s},\n' % l for l in lines) + '};\n', encoding='utf-8')
print(f'splash_badge.h: {WIDTH} x {h}')
